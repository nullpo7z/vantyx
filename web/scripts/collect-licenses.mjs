/**
 * Collect the license texts of every runtime dependency that Vite compiles into
 * the shipped bundle, and write them to public/THIRD-PARTY-LICENSES.txt so the
 * file is served at /THIRD-PARTY-LICENSES.txt and lands in the container image.
 *
 * Why: minification strips the licence banners from the bundle, but MIT
 * requires the copyright notice to travel with the distributed copies, and
 * MPL-2.0 §3.2 requires executable distributions to carry the licence notice
 * and tell recipients where the source is. noVNC is MPL-2.0.
 *
 * No extra npm dependency: this walks node_modules directly. Run from web/
 * (the `prebuild` script does).
 */
import { readFileSync, writeFileSync, readdirSync, existsSync, mkdirSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const webRoot = resolve(here, '..')
const nodeModules = join(webRoot, 'node_modules')
const outFile = join(webRoot, 'public', 'THIRD-PARTY-LICENSES.txt')

const LICENSE_FILE = /^(LICENSE|LICENCE|COPYING)(\.(txt|md))?$/i
/** Packages whose source is available upstream; recorded for MPL-2.0 §3.2. */
const SOURCE_URLS = {
  '@novnc/novnc': 'https://github.com/novnc/noVNC',
  'asciinema-player': 'https://github.com/asciinema/asciinema-player',
  '@xterm/xterm': 'https://github.com/xtermjs/xterm.js',
  '@xterm/addon-fit': 'https://github.com/xtermjs/xterm.js',
  '@xterm/addon-web-links': 'https://github.com/xtermjs/xterm.js',
}

/** @returns {string[]} runtime dependency names, including transitive ones. */
function runtimeDeps() {
  const pkg = JSON.parse(readFileSync(join(webRoot, 'package.json'), 'utf8'))
  const seen = new Set()
  const queue = Object.keys(pkg.dependencies || {})
  while (queue.length) {
    const name = queue.shift()
    if (seen.has(name)) continue
    const manifest = join(nodeModules, name, 'package.json')
    if (!existsSync(manifest)) continue
    seen.add(name)
    const meta = JSON.parse(readFileSync(manifest, 'utf8'))
    queue.push(...Object.keys(meta.dependencies || {}))
  }
  return [...seen].sort()
}

function licenseText(dir) {
  const file = readdirSync(dir).find((f) => LICENSE_FILE.test(f))
  return file ? readFileSync(join(dir, file), 'utf8').trimEnd() : null
}

const names = runtimeDeps()
const blocks = []
const missing = []

for (const name of names) {
  const dir = join(nodeModules, name)
  const meta = JSON.parse(readFileSync(join(dir, 'package.json'), 'utf8'))
  const spdx = typeof meta.license === 'string' ? meta.license : (meta.license?.type ?? 'UNKNOWN')
  const text = licenseText(dir)
  if (!text) missing.push(name)
  const source = SOURCE_URLS[name] || meta.repository?.url || meta.homepage || '(see npm)'
  blocks.push(
    [
      '='.repeat(80),
      `${name}@${meta.version}`,
      `License: ${spdx}`,
      `Source:  ${source.replace(/^git\+/, '').replace(/\.git$/, '')}`,
      '='.repeat(80),
      '',
      text || `(No license file shipped in the package; declared as ${spdx}.)`,
      '',
    ].join('\n'),
  )
}

const header = `Third-party licenses bundled in the Vantyx web assets
=====================================================

The JavaScript served from /assets is a compiled bundle that includes the
packages listed below. Minification removes their banner comments, so the
original license texts are reproduced here in full.

@novnc/novnc is licensed under the Mozilla Public License 2.0. It is included
unmodified; its source can be obtained from https://github.com/novnc/noVNC.

Vantyx itself is licensed under the Apache License 2.0 (see LICENSE / NOTICE).

Generated by web/scripts/collect-licenses.mjs — do not edit by hand.
Packages: ${names.length}

`

mkdirSync(dirname(outFile), { recursive: true })
writeFileSync(outFile, header + blocks.join('\n'), 'utf8')

if (missing.length) {
  console.warn(`collect-licenses: no license file found for: ${missing.join(', ')}`)
}
console.log(`collect-licenses: wrote ${outFile} (${names.length} packages)`)
